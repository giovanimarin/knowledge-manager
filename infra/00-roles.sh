#!/bin/bash
set -euo pipefail
psql -X --set ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'SQL'
\getenv app_password KM_APP_PASSWORD
REVOKE ALL ON DATABASE km FROM PUBLIC;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE ROLE km_migrate NOLOGIN NOSUPERUSER NOBYPASSRLS;
CREATE ROLE km_app LOGIN NOSUPERUSER NOBYPASSRLS PASSWORD :'app_password';
GRANT CONNECT ON DATABASE km TO km_app;
SQL
